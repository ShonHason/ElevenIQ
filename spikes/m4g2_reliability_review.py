"""
Writes docs/reviews/m4g2-reliability.md (plan 005 M4g2, ADR 004 §13.6) from the committed
measurements (src/eleveniq/analytics/measurements/statsbomb_27.json, read as data) and the
report-only cells file data/processed/reports/m4g2_reliability_cells.json, both written by
spikes/m4_decision_measurements.py --write-json and checked by
spikes/m4g2_reliability_reference.py --check-output.

Sections: method and K; odd/even vs multi-split (z per cell); the ratios' n per split;
minute-bucket reliability (report only, no status change follows from it).

No eleveniq imports (tests/test_spikes_independent.py).

Usage: .venv/bin/python spikes/m4g2_reliability_review.py [--out PATH]
"""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MEASUREMENTS = ROOT / "src" / "eleveniq" / "analytics" / "measurements" / "statsbomb_27.json"
CELLS = ROOT / "data" / "processed" / "reports" / "m4g2_reliability_cells.json"
OUT = ROOT / "docs" / "reviews" / "m4g2-reliability.md"
GROUPS = ("CB", "FB-WB", "DM-CM", "AM-Winger", "ST")
BUCKETS = ("900-1350", "1350-2000", ">=2000")
DNA_MIN, LOW_BELOW, MARGIN = 0.6, 0.7, 0.02      # ADR 004 §10.3, written out
Z_LIST = 2.0
# The stats-reviewer's read-only test of the hypotheses (/finish-chunk, 2026-10-07; ADR 004
# §13.6). Its figures come from that test, not from this script.
ODD_EVEN_TEST = (
    "**Outcome of the test (stats-reviewer, 2026-10-07; 400 random splits with the engine's split "
    "functions; ADR 004 §13.6):**\n\n"
    "- **The optimism is real:** the odd/even split hits every cell at once, so cell z values are "
    "correlated; allowing for that, the cross-cell mean z over random splits has SD 0.111, and "
    "odd/even's +0.25–0.27 has P ≈ 0.007.\n"
    "- **Temporal balance: confirmed.** A time-balanced random split (randomised within "
    "consecutive match pairs) gives mean z +0.175, and odd/even sits inside that distribution; a "
    "first-half vs second-half split gives −0.87 (within-season drift is substantial).\n"
    "- **Home/away: rejected.** A home vs away split gives z −0.07; odd/even halves are less "
    "home/away-balanced than random ones (mean |Δ home share| 0.29 vs 0.16), which pushes r down.\n"
    "- **Consequence:** random splits count within-season drift as error, while for a season "
    "aggregate it is part of the true value, so multi-split r_full understates a season "
    "aggregate's reliability by about 0.004–0.008 on average (conservative). The method stands; "
    "a time-stratified random split is the alternative if a later ADR wants one.")


def f3(v: float | None) -> str:
    return "—" if v is None else f"{v:.3f}"


def table(head: list[str], rows: list[list[str]]) -> list[str]:
    return ["| " + " | ".join(head) + " |", "|" + "|".join(" --- " for _ in head) + "|",
            *("| " + " | ".join(r) + " |" for r in rows)]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    m = json.loads(MEASUREMENTS.read_text())
    cells = json.loads(CELLS.read_text())
    rel = m["reliability"]
    if cells["k"] != rel["k"] or cells["seed"] != rel["seed"]:
        raise SystemExit("the cells report and the measurements differ in K or seed")

    per90 = [(name, g, c) for name, spec in sorted(m["metrics"].items())
             for g, c in spec["groups"].items()]
    z = [(name, g, (c["r_full_odd_even"] - c["r_full"]) / c["r_full_sd"])
         for name, g, c in per90
         if c["r_full"] is not None and c["r_full_odd_even"] is not None and c["r_full_sd"]]
    zs = [v for _, _, v in z]
    shift = [c["r_full"] - c["r_full_odd_even"] for _, _, c in per90
             if c["r_full"] is not None and c["r_full_odd_even"] is not None]
    se = [c["r_full_mc_se"] for _, _, c in per90 if c["r_full_mc_se"] is not None]

    L = ["# M4g2 — Multi-split reliability (plan 005 M4g2, ADR 004 §13.6)", "",
         "Generated by `spikes/m4g2_reliability_review.py` from the committed measurements "
         f"(`{MEASUREMENTS.relative_to(ROOT)}`, K = {rel['k']}) and `{CELLS.relative_to(ROOT)}`. "
         "Both are checked value by value by `spikes/m4g2_reliability_reference.py --check-output`.",
         "", "## Method", "",
         "- Per split, each stint's matches go at random to two equal halves (odd count: a coin "
         "decides which half gets the extra match); one generator, "
         f"`default_rng({rel['seed']})`, draws in a fixed order; one assignment per split serves "
         "every cell.",
         "- Per split and cell: half values demeaned within league × group, pooled Pearson r_k, "
         "Spearman-Brown; r_full = the mean of the corrected values over the splits.",
         f"- K starts at {rel['k_start']} and doubles until every judged cell's MC SE ≤ "
         f"{rel['mc_se_target']}, capped at {rel['k_cap']}. **K = {rel['k']}; cap reached: "
         f"{rel['reached_cap']}.** Judged cells still above the target: "
         + (", ".join(f"{g} `{c}`" for g, c in rel["judged_cells_above_target"]) or "none") + ".",
         f"- Per-90 gated cells: MC SE median {statistics.median(se):.4f}, max {max(se):.4f}.",
         "- MC errors are correlated across cells (one assignment per split), so a count of cells "
         "crossing 0.6 is not a count of independent events. Sampling error over players "
         "(SE ≈ 0.04) is unchanged: cells near 0.6 stay fragile.",
         "", "## Odd/even vs multi-split", "",
         f"z = (odd/even − multi-split mean) / SD over the splits, {len(zs)} per-90 gated cells: "
         f"mean {statistics.mean(zs):+.2f}, SD {statistics.stdev(zs):.2f}; |z| > 2: "
         f"{sum(abs(v) > 2 for v in zs)}, |z| > 3: {sum(abs(v) > 3 for v in zs)}. Mean shift "
         f"(multi-split − odd/even) {statistics.mean(shift):+.4f}.", "",
         "**Hypotheses (user, 2026-10-07):** alternating dates spread both halves over the whole "
         "season, so form, injuries and coach changes are shared (temporal balance), while random "
         "halves can cluster in time; home/away alternation alone would more likely lower r than "
         "raise it. No change here is \"improved reliability\": both methods estimate the same "
         "quantity, the new one with less split noise.", "",
         ODD_EVEN_TEST, "",
         f"Cells with |z| > {Z_LIST:g}, or whose two values sit on different sides of "
         f"{DNA_MIN} or {LOW_BELOW}:", ""]
    rows = []
    for name, g, c in per90:
        oe, mu, sd = c["r_full_odd_even"], c["r_full"], c["r_full_sd"]
        if oe is None or mu is None or not sd:
            continue
        zz = (oe - mu) / sd
        cross = [t for t in (DNA_MIN, LOW_BELOW) if (oe >= t) != (mu >= t)]
        if abs(zz) > Z_LIST or cross:
            rows.append([g, f"`{name}`", f3(oe), f3(mu), f"{sd:.3f}", f"{zz:+.2f}",
                         ", ".join(f"{t:g}" for t in cross) or "—"])
    rows.sort(key=lambda r: (GROUPS.index(r[0]), r[1]))
    L += table(["Group", "Metric", "Odd/even", "Multi-split", "SD", "z", "Crosses"], rows)

    L += ["", "## Ratios and team_pass_share: rows per split", "",
          "The rows with attempts in both halves change per split.", ""]
    rows = []
    for name, spec in sorted(m["ratios"].items()):
        for g in GROUPS:
            c = spec["groups"][g]
            p = "split_half_r_full"
            rows.append([f"`{name}`", g, f3(c[p + "_odd_even"]), f3(c[p]), f3(c[p + "_mc_se"]),
                         f"{c[p + '_n_min']}–{c[p + '_n_max']} (median {c[p + '_n_median']:g})",
                         f3(c[p + "_share_present_every_split"])])
    for g, c in sorted(m["team_pass_share"].items()):
        p = "split_half_r_full"
        rows.append(["`team_pass_share`", g, f3(c[p + "_odd_even"]), f3(c[p]), f3(c[p + "_mc_se"]),
                     f"{c[p + '_n_min']}–{c[p + '_n_max']} (median {c[p + '_n_median']:g})",
                     f3(c[p + "_share_present_every_split"])])
    L += table(["Measure", "Group", "Odd/even", "Multi-split", "MC SE", "n per split",
                "Share in every split"], rows)

    by = {(c["population"], c["group"], c["measure"]): c for c in cells["cells"]}
    L += ["", "## Minute buckets (report only)", "",
          "Multi-split r_full on the gated rows split by nominal minutes: 900–1350, 1350–2000, "
          "≥ 2000; n = stints with both halves (median over splits). **No status change follows "
          "from it**; a gate or note change needs a new ADR entry. Buckets select on minutes, which "
          "go with role and stability, so the spread between players also differs by bucket; ST "
          "buckets of about 50 rows have an SE ≈ 0.1. Cells with r undefined in some splits report "
          "the defined ones (`n_undefined`).", "",
          "### Pooled over groups (demeaned within league × group)", ""]
    rows = []
    for name in sorted({k[2] for k in by}):
        r = [f"`{name}`", f3(by[("gate", "ALL", name)]["r_full"])]
        for b in BUCKETS:
            c = by[(b, "ALL", name)]
            r.append(f"{f3(c['r_full'])} ({c['n_median']:g})")
        rows.append(r)
    L += table(["Measure", "Gated", *[f"{b} (n)" for b in BUCKETS]], rows)
    L += ["", "### Mean over the per-90 measures, per group", ""]
    rows = []
    for g in GROUPS:
        r = [g]
        for pop in ("gate", *BUCKETS):
            vals = [c["r_full"] for (p, gg, n), c in by.items()
                    if p == pop and gg == g and n.endswith("_p90") and c["r_full"] is not None]
            ns = [c["n_median"] for (p, gg, n), c in by.items()
                  if p == pop and gg == g and n.endswith("_p90")]
            r.append(f"{statistics.mean(vals):.3f} (n {statistics.median(ns):g})")
        rows.append(r)
    L += table(["Group", "Gated", *BUCKETS], rows)
    partly = sorted(f"{p} {g} `{n}` ({c['n_undefined']})" for (p, g, n), c in by.items()
                    if 0 < c["n_undefined"] < cells["k"])
    L += ["", f"Cells with r undefined in some splits ({len(partly)}): " + "; ".join(partly) + ".", ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(L))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
