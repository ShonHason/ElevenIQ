// Generate src/types/contract.ts from contract/v1/*.schema.json (ADR 005 §2). Deterministic;
// `node scripts/gen-types.mjs --check` fails when the committed file is stale.
import { compileFromFile } from "json-schema-to-typescript";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "..", "contract", "v1");
const out = join(here, "..", "src", "types", "contract.ts");
const names = ["common", "manifest", "search-index", "labels", "group", "player", "style-map", "gems"];
let text = "// Generated by scripts/gen-types.mjs from contract/v1. Do not edit.\n/* eslint-disable */\n";
const seen = new Set();
for (const n of names) {
  const ts = await compileFromFile(join(dir, `${n}.schema.json`), {
    bannerComment: "", cwd: dir, additionalProperties: false, unreachableDefinitions: n === "common",
    declareExternallyReferenced: true, format: true, style: { singleQuote: false },
  });
  for (const block of ts.split(/\n(?=export )/)) {
    const name = /export (?:interface|type) (\w+)/.exec(block)?.[1];
    if (name && seen.has(name)) continue;
    if (name) seen.add(name);
    text += block.trimEnd() + "\n";
  }
}
if (process.argv.includes("--check")) {
  const now = readFileSync(out, "utf8");
  if (now !== text) { console.error("src/types/contract.ts is stale: run npm run types"); process.exit(1); }
  console.log("types up to date");
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
